"""
Block copolymers: chains of blocks, each block's tail bonded to the next block's head
"""

from typing import Mapping, Optional, Sequence

import numpy as np
from networkx import Graph

from ...graphs.generators import path_graph_from_sequence
from ...mupr.primitives import Primitive

from .._common import EDGE_JOINS, NODE_COMPONENT, ComponentLabel
from ..exceptions import CompatibilityError
from ..rules.compatibility import CompatibilityRule
from ..rules.junctions import JunctionRule
from ..utils.compose import namespace_label
from .base import CompositeGenerator, TopologyGenerator


class BlockCopolymerGenerator(CompositeGenerator):
    """
    Generator of block copolymers: two or more blocks joined end to end

    Each block is generated by its own component, so it brings its own units, size,
    sequence, tacticity and end groups; the chain's length is the sum of its blocks'.
    Between consecutive blocks, the compatibility rule picks which free faces bond
    (by default the upstream block's free tail and the downstream block's free head).

    The chain's outer ends are whatever the first and last blocks leave there (capped or
    free); ends between blocks must be left free. Tacticity isn't carried across joins.

    Parameters
    ----------
    components : Mapping[str, TopologyGenerator]
        The block generators, by label, e.g. {'PS': ps_generator, 'PMMA': pmma_generator}
    blocks : Sequence[str]
        Component labels in chain order, head first, e.g. ('PS', 'PMMA', 'PS'); a label
        may repeat, and each occurrence is generated independently
    compatibility : CompatibilityRule, optional
        Which free faces bond between blocks; defaults to head_to_tail()
    junctions : JunctionRule, optional
        How strands pair where blocks join (for ladder blocks); defaults to FixedPairing
    """

    def __init__(
        self,
        components: Mapping[ComponentLabel, TopologyGenerator | str | Primitive],
        blocks: Sequence[ComponentLabel],
        *,
        compatibility: Optional[CompatibilityRule] = None,
        junctions: Optional[JunctionRule] = None,
    ) -> None:
        super().__init__(components, compatibility=compatibility, junctions=junctions)

        self.blocks: tuple[ComponentLabel, ...] = tuple(blocks)
        if len(self.blocks) < 2:
            raise ValueError(f"A block copolymer needs at least two blocks, got {len(self.blocks)}")
        if unknown := [label for label in self.blocks if label not in self._components]:
            raise ValueError(f"Block(s) {unknown} aren't among the components {list(self._components)}")
        self._warn_unused(self.blocks)

        # each join must be possible, when the blocks say which sites they can leave free
        for upstream, downstream in zip(self.blocks, self.blocks[1:]):
            self._check_joinable(upstream, downstream)

    def _check_joinable(self, upstream: ComponentLabel, downstream: ComponentLabel) -> None:
        """Raise if no free site of one block can bond to any free site of the next"""
        sites_u = self._components[upstream].possible_free_sites()
        sites_v = self._components[downstream].possible_free_sites()
        if (sites_u is None) or (sites_v is None):
            return  # unknown until generation

        ups = [(namespace_label(upstream, label), face) for label, face in sites_u]
        downs = [(namespace_label(downstream, label), face) for label, face in sites_v]
        if not any(self.compatibility.compatible(up, down) for up in ups for down in downs):
            raise CompatibilityError(
                f"Block {upstream!r} can't join block {downstream!r}: none of its free sites "
                f"{sorted(map(str, sites_u))} are compatible with {sorted(map(str, sites_v))} "
                f"(an end between blocks may be capped)"
            )

    def component_graph(self, rng: np.random.Generator) -> Graph:
        """A path of blocks; the compatibility rule finds each join's faces"""
        coarse = path_graph_from_sequence(self.blocks, label_attr=NODE_COMPONENT)
        for i in range(len(self.blocks) - 1):
            coarse.edges[i, i + 1][EDGE_JOINS] = ((i, None), (i + 1, None))
        return coarse

    def __repr__(self) -> str:
        return f"BlockCopolymerGenerator(blocks={self.blocks}, compatibility={self.compatibility!r})"
